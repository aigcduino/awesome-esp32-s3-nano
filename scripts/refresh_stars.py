#!/usr/bin/env python3
"""Refresh data/stars.json from the GitHub API.

Set GITHUB_TOKEN to lift the 60 req/h anonymous limit (5000 req/h authenticated).
The token is read from the environment only and never written to disk.

Usage:
    GITHUB_TOKEN=$(gh auth token) python3 scripts/refresh_stars.py
"""

from __future__ import annotations

import json
import os
import ssl
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "projects.yml"
STARS = ROOT / "data" / "stars.json"
UA = "awesome-esp32-s3-nano star refresher"

def ssl_context() -> "ssl.SSLContext":
    """Prefer certifi: stock macOS/Windows Pythons often ship without a CA bundle."""
    try:
        import certifi
    except ImportError:
        return ssl.create_default_context()
    return ssl.create_default_context(cafile=certifi.where())


CTX = ssl_context()


def load_repos() -> list[str]:
    import yaml

    data = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    return [p["repo"] for p in data["projects"]]


def get_stars(repo: str, token: str | None) -> int | None:
    headers = {"User-Agent": UA, "Accept": "application/vnd.github+json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}", headers=headers)
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=20, context=CTX) as resp:
                return json.load(resp).get("stargazers_count")
        except urllib.error.HTTPError as exc:
            if exc.code in (403, 429):
                time.sleep(5 * (attempt + 1))
                continue
            print(f"  {repo}: HTTP {exc.code}", file=sys.stderr)
            return None
        except Exception as exc:  # noqa: BLE001
            print(f"  {repo}: {type(exc).__name__}", file=sys.stderr)
            return None
    return None


def main() -> int:
    token = os.environ.get("GITHUB_TOKEN") or None
    previous = json.loads(STARS.read_text(encoding="utf-8")) if STARS.exists() else {}
    stars: dict[str, int] = dict(previous.get("repos", {}))

    repos = load_repos()
    changed = 0
    for repo in repos:
        value = get_stars(repo, token)
        if value is None:
            continue
        if stars.get(repo) != value:
            changed += 1
        stars[repo] = value

    out = {
        "snapshot": time.strftime("%Y-%m-%d"),
        "note": previous.get("note", "Machine-generated by scripts/refresh_stars.py."),
        "repos": dict(sorted(stars.items())),
    }
    STARS.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"{len(repos)} repos, {changed} changed, snapshot {out['snapshot']}")
    print("Now run: python3 scripts/build.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
