#!/usr/bin/env python3
"""Generate the project sections of README.md / README.zh-CN.md from data/projects.yml.

Usage:
    python3 scripts/build.py          # rewrite the READMEs in place
    python3 scripts/build.py --check  # exit 1 if the READMEs are out of date (CI)

Only the region between the BEGIN/END markers is touched; everything else in the
READMEs is hand-written prose and stays untouched.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "projects.yml"
STARS = ROOT / "data" / "stars.json"

BEGIN = "<!-- BEGIN PROJECTS -->"
END = "<!-- END PROJECTS -->"

LANGS = {
    "en": {
        "readme": "README.md",
        "contents": "Contents",
        "footer": "_Star counts: snapshot of {date}._",
    },
    "zh": {
        "readme": "README.zh-CN.md",
        "contents": "目录",
        "footer": "_星标数为 {date} 的快照。_",
    },
}

SUPPORT_LABEL = {
    "en": {"generic": "generic ESP32-S3", "none": "no board support"},
    "zh": {"generic": "通用 ESP32-S3", "none": "无板级支持"},
}


def load_yaml(path: Path) -> dict:
    try:
        import yaml
    except ImportError:  # pragma: no cover
        sys.exit("PyYAML is required: python3 -m pip install pyyaml")
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def load_stars() -> dict:
    if not STARS.exists():
        return {}
    return json.loads(STARS.read_text(encoding="utf-8")).get("repos", {})


def fmt_stars(n: int) -> str:
    if n >= 1000:
        return f"{n / 1000:.1f}k".replace(".0k", "k")
    return str(n)


def slug(text: str) -> str:
    """Approximate GitHub's heading anchor algorithm."""
    s = text.lower()
    s = re.sub(r"[^\w\s-]", "", s)
    return s.replace(" ", "-")


def validate(data: dict) -> None:
    sections = [s["id"] for s in data["sections"]]
    seen_ids: set[str] = set()
    for s in sections:
        if s in seen_ids:
            sys.exit(f"duplicate section id: {s}")
        seen_ids.add(s)

    seen_repos: set[str] = set()
    for p in data["projects"]:
        repo = p["repo"]
        if repo in seen_repos:
            sys.exit(f"duplicate repo: {repo}")
        seen_repos.add(repo)
        if p["section"] not in seen_ids:
            sys.exit(f"{repo}: unknown section {p['section']!r}")
        for field in ("en", "zh"):
            if not p.get(field):
                sys.exit(f"{repo}: missing {field} description")
        if p.get("support") not in ("full", "generic", "none"):
            sys.exit(f"{repo}: bad support value {p.get('support')!r}")


def render(data: dict, stars: dict, lang: str) -> str:
    meta = data["meta"]
    sections = data["sections"]
    by_section: dict[str, list[dict]] = {s["id"]: [] for s in sections}
    for p in data["projects"]:
        by_section[p["section"]].append(p)

    out: list[str] = []
    out.append(BEGIN)
    out.append(
        f"<!-- generated by scripts/build.py from data/projects.yml — do not edit by hand -->"
    )
    out.append("")

    # table of contents
    out.append(f"## {LANGS[lang]['contents']}")
    out.append("")
    for s in sections:
        title = s[lang]
        out.append(f"- [{title}](#{slug(title)})")
    out.append("")

    for s in sections:
        entries = by_section[s["id"]]
        if not entries:
            continue
        out.append(f"## {s[lang]}")
        out.append("")
        for p in entries:
            url = f"https://github.com/{p['repo']}"
            desc = " ".join(p[lang].split())
            suffix_parts: list[str] = []
            support = p.get("support", "full")
            if support in ("generic", "none"):
                suffix_parts.append(SUPPORT_LABEL[lang][support])
            n = stars.get(p["repo"])
            if n is not None:
                suffix_parts.append(f"★{fmt_stars(n)}")
            suffix = f" *({', '.join(suffix_parts)})*" if suffix_parts else ""
            out.append(f"- [{p['repo']}]({url}) - {desc}{suffix}")
        out.append("")

    out.append(LANGS[lang]["footer"].format(date=meta["star_snapshot"]))
    out.append(END)
    return "\n".join(out)


def splice(existing: str, block: str, path: Path) -> str:
    if BEGIN not in existing or END not in existing:
        sys.exit(f"{path.name}: missing {BEGIN} / {END} markers")
    head, rest = existing.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{block}{tail}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if READMEs are stale")
    args = ap.parse_args()

    data = load_yaml(DATA)
    validate(data)
    stars = load_stars()

    stale: list[str] = []
    for lang, cfg in LANGS.items():
        path = ROOT / cfg["readme"]
        if not path.exists():
            sys.exit(f"missing {cfg['readme']}")
        existing = path.read_text(encoding="utf-8")
        updated = splice(existing, render(data, stars, lang), path)
        if updated != existing:
            stale.append(cfg["readme"])
            if not args.check:
                path.write_text(updated, encoding="utf-8")

    if args.check:
        if stale:
            print("READMEs are out of date: " + ", ".join(stale))
            print("Run: python3 scripts/build.py")
            return 1
        print("READMEs are up to date.")
        return 0

    print("updated: " + (", ".join(stale) if stale else "nothing changed"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
